 then alter publication supabase_realtime add table public.chat_messages; end if;
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='song_comments')
 then alter publication supabase_realtime add table public.song_comments; end if;
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='private_messages')
 then alter publication supabase_realtime add table public.private_messages; end if;
end $$;
