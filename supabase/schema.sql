-- Run once in a new Supabase project's SQL Editor.
-- Real auth, public chat and song comments, and private messages.
-- Never expose service_role keys in GitHub Pages. All client writes use RLS.
create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null default 'Člen komunity' check (char_length(display_name) between 2 and 40),
 created_at timestamptz not null default now()
);
create table if not exists public.chat_messages(
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 body text not null check (char_length(trim(body)) between 1 and 800),
 created_at timestamptz not null default now()
);
create table if not exists public.song_comments(
 id bigint generated by default as identity primary key,
 song_id text not null check (song_id ~ '^[0-9a-f-]{36}$'),
 user_id uuid not null references public.profiles(id) on delete cascade,
 body text not null check (char_length(trim(body)) between 1 and 800),
 created_at timestamptz not null default now()
);
create table if not exists public.private_messages(
 id bigint generated by default as identity primary key,
 sender_id uuid not null references public.profiles(id) on delete cascade,
 recipient_id uuid not null references public.profiles(id) on delete cascade,
 body text not null check (char_length(trim(body)) between 1 and 800),
 created_at timestamptz not null default now(),
 check (sender_id <> recipient_id)
);
create index if not exists chat_messages_date on public.chat_messages(created_at desc);
create index if not exists song_comments_song on public.song_comments(song_id,created_at desc);
create index if not exists private_messages_from on public.private_messages(sender_id,recipient_id,created_at desc);
create index if not exists private_messages_to on public.private_messages(recipient_id,sender_id,created_at desc);

create or replace function public.create_user_profile()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,display_name)
 values(new.id,
   case
    when char_length(trim(coalesce(new.raw_user_meta_data->>'display_name',''))) between 2 and 40
      then trim(new.raw_user_meta_data->>'display_name')
    else 'Člen komunity'
   end)
 on conflict (id) do nothing;
 return new;
end;$$;

drop trigger if exists on_auth_user_created_luky on auth.users;
create trigger on_auth_user_created_luky after insert on auth.users
for each row execute procedure public.create_user_profile();

alter table public.profiles enable row level security;
alter table public.chat_messages enable row level security;
alter table public.song_comments enable row level security;
alter table public.private_messages enable row level security;

drop policy if exists "People can see profiles" on public.profiles;
create policy "People can see profiles" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "Create own profile" on public.profiles;
create policy "Create own profile" on public.profiles for insert to authenticated with check (auth.uid()=id);
drop policy if exists "Update own profile" on public.profiles;
create policy "Update own profile" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id);

drop policy if exists "Read community chat" on public.chat_messages;
create policy "Read community chat" on public.chat_messages for select to anon, authenticated using (true);
drop policy if exists "Send signed-in chat" on public.chat_messages;
create policy "Send signed-in chat" on public.chat_messages for insert to authenticated with check (auth.uid()=user_id);

drop policy if exists "Read comments" on public.song_comments;
create policy "Read comments" on public.song_comments for select to anon, authenticated using (true);
drop policy if exists "Comment signed in" on public.song_comments;
create policy "Comment signed in" on public.song_comments for insert to authenticated with check (auth.uid()=user_id);

drop policy if exists "Only participants read DMs" on public.private_messages;
create policy "Only participants read DMs" on public.private_messages for select to authenticated
 using (auth.uid()=sender_id or auth.uid()=recipient_id);
drop policy if exists "Sender can send DM" on public.private_messages;
create policy "Sender can send DM" on public.private_messages for insert to authenticated
 with check (auth.uid()=sender_id and recipient_id<>sender_id);

